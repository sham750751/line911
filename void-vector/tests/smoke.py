from pathlib import Path
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler
from functools import partial
from threading import Thread
import json
import os
import shutil
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'test-output'
OUT.mkdir(exist_ok=True)
server = ThreadingHTTPServer(('127.0.0.1', 0), partial(SimpleHTTPRequestHandler, directory=str(ROOT / 'android/assets')))
Thread(target=server.serve_forever, daemon=True).start()
url = f'http://127.0.0.1:{server.server_port}/game.html?qa=1'
checks = []
errors = []
def check(name, ok):
    assert ok, name
    checks.append(name)
    print('PASS', name, flush=True)

with sync_playwright() as p:
    executable = os.environ.get('CHROME_BIN') or shutil.which('google-chrome') or shutil.which('chromium')
    browser = p.chromium.launch(headless=True, executable_path=executable, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':412,'height':915}, device_scale_factor=2, is_mobile=True, has_touch=True)
    page = context.new_page()
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(url)
    page.wait_for_function('window.VVTest')
    snap = lambda: page.evaluate('VVTest.snapshot()')
    check('menu and logo visible', page.locator('#menu').is_visible() and page.locator('.brand .logo').is_visible())
    page.screenshot(path=str(OUT/'01-menu.png'))
    page.locator('#helpBtn').tap()
    check('instructions open', page.locator('#help').is_visible())
    page.locator('#helpClose').tap()
    page.locator('#startBtn').tap()
    check('start with three lives', snap()['mode']=='play' and snap()['player']['hp']==3)
    page.touchscreen.tap(95,650)
    page.wait_for_timeout(400)
    check('real touch moves ship', snap()['player']['x']<140)
    page.evaluate('VVTest.setPlayer({inv:0,shield:0,hp:3});let s=VVTest.snapshot();VVTest.addBullet(s.player.x,s.player.y);VVTest.step(.02)')
    check('bullet collision costs one life', snap()['player']['hp']==2)
    page.evaluate('let s=VVTest.snapshot();VVTest.addBullet(s.player.x,s.player.y);VVTest.step(.02)')
    check('invulnerability prevents instant double damage', snap()['player']['hp']==2)
    page.evaluate('VVTest.setPlayer({inv:0,shield:10});VVTest.hit()')
    check('shield absorbs hit', snap()['player']['hp']==2 and snap()['player']['shield']==0)
    page.evaluate('VVTest.setPlayer({inv:5,fire:0,tx:100,x:100,ty:600,y:600});VVTest.addEnemy(100,520,1);VVTest.step(.4)')
    check('automatic fire destroys enemies and awards score', snap()['kills']>=1 and snap()['score']>0)
    page.locator('#pauseBtn').tap()
    before = snap()
    page.evaluate('VVTest.step(2)')
    check('pause freezes gameplay', snap()['mode']=='pause' and snap()['player']==before['player'])
    page.locator('#resumeBtn').tap()
    page.evaluate('let s=VVTest.snapshot();VVTest.addBullet(40,300);VVTest.addEnemy(40,200);VVTest.pulse()')
    check('pulse consumes charge and clears hazards', snap()['player']['bombs']==0 and snap()['hostile']==0 and not snap()['enemies'])
    page.evaluate('VVTest.setPlayer({bombs:0});VVTest.pulse()')
    check('empty pulse cannot become negative', snap()['player']['bombs']==0)
    page.evaluate('VVTest.clearWave()')
    offered = page.evaluate('VVTest.upgrades()')
    check('wave offers three distinct upgrades', snap()['mode']=='upgrades' and len(set(offered))==3)
    page.screenshot(path=str(OUT/'03-upgrades.png'))
    page.locator('.upgrade').first.tap()
    check('upgrade resumes next wave', snap()['mode']=='play' and snap()['wave']==2)
    page.evaluate('VVTest.setWave(3);VVTest.setPlayer({inv:99,bombs:5,hp:3});VVTest.step(2)')
    check('third wave spawns boss', snap()['boss'] is not None and page.locator('#bossHud').is_visible())
    page.screenshot(path=str(OUT/'02-boss.png'))
    page.evaluate('for(let i=0;i<4;i++)VVTest.pulse();VVTest.step(.05)')
    check('boss defeat gives score and repairs', snap()['boss'] is None and snap()['score']>=1900)
    page.evaluate('VVTest.step(1.5)')
    check('boss wave progresses to upgrade selection', snap()['mode']=='upgrades')
    page.locator('.upgrade').first.tap()
    page.evaluate('VVTest.setPlayer({hp:1,inv:0,shield:0});VVTest.hit()')
    result = snap()
    check('zero lives opens game over', result['mode']=='over' and page.locator('#over').is_visible())
    check('best score recorded', result['best']==int(result['score']))
    page.screenshot(path=str(OUT/'04-game-over.png'))
    page.locator('#retryBtn').tap()
    check('retry resets player and score', snap()['mode']=='play' and snap()['score']==0 and snap()['player']['hp']==3)
    page.reload()
    page.wait_for_function('window.VVTest')
    check('record survives page restart', snap()['best']==result['best'])
    page.locator('.soundBtn').first.tap()
    page.reload()
    check('sound preference persists', 'выкл.' in page.locator('.soundBtn').first.inner_text())
    page.set_viewport_size({'width':360,'height':640})
    page.wait_for_timeout(150)
    box = page.locator('#startBtn').bounding_box()
    check('small phone start button fits', box['y']>=0 and box['y']+box['height']<=640)
    page.screenshot(path=str(OUT/'05-small-phone.png'))
    page.locator('#startBtn').tap()
    page.evaluate('VVTest.clearWave()')
    box = page.locator('.upgrade').last.bounding_box()
    check('small phone upgrade cards fit', box['y']+box['height']<=640)
    check('no JavaScript runtime errors', not errors)
    context.close()
    browser.close()
server.shutdown()
(OUT/'checks.json').write_text(json.dumps({'passed':checks,'errors':errors},ensure_ascii=False,indent=2))
print(f'{len(checks)} checks passed')
